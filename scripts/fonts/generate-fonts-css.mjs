#!/usr/bin/env node
// Writes src/fonts.css: the same @font-face rules @fontsource ships for the
// reader's three bundled families, but with the woff2 source only.
//
// Why: @fontsource lists `url(x.woff2) format('woff2'), url(x.woff) format('woff')`
// for every face, so Vite bundles BOTH files for every one - about 1.2 MB of
// .woff the app never loads, since every WebView this app can run on (Android
// System WebView is Chromium; woff2 landed in Chrome 36, and the app's own
// build target is Chrome 111) supports woff2. The unicode-range subsets
// (latin, latin-ext, cyrillic, greek, vietnamese) are kept exactly as they were.
//
//   node scripts/fonts/generate-fonts-css.mjs
//
// Re-run it (and commit src/fonts.css) after upgrading an @fontsource package.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const families = ['literata', 'merriweather', 'atkinson-hyperlegible'];
const faces = ['400', '400-italic', '700', '700-italic'];

let out = `/* GENERATED by scripts/fonts/generate-fonts-css.mjs - do not edit by hand.
   @fontsource's @font-face rules with the woff2 source only (no .woff). */\n`;
let blocks = 0;

for (const family of families) {
  for (const face of faces) {
    const css = readFileSync(join(repo, 'node_modules/@fontsource', family, `${face}.css`), 'utf8');
    for (const block of css.match(/\/\*[^*]*\*\/\s*@font-face\s*\{[^}]*\}/g) ?? []) {
      const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)\s*format\('woff2'\)/.exec(block);
      if (!woff2) throw new Error(`no woff2 source in a ${family} ${face} block`);
      const rewritten = block.replace(/src:[^;]*;/, `src: url(../node_modules/@fontsource/${family}/files/${woff2[1]}) format('woff2');`);
      out += `\n${rewritten}\n`;
      blocks++;
    }
  }
}

writeFileSync(join(repo, 'src/fonts.css'), out);
console.log(`wrote src/fonts.css (${blocks} @font-face rules, woff2 only)`);
